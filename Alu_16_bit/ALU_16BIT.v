`timescale 1ns / 1ps

module Alu_16_bit(
    input  [15:0] A,
    input  [15:0] B,
    input  [3:0]  imm,
    input  carry_in,// Old CF from flag register
    input  [3:0]  ALU_op,
    input  [2:0] Shift_type,
    input  B_select_imm,//im conserding every sub_op code lsb to be associate with decision of whether its a,b or a,imm
    input  use_carry_in, // signal generated by instruction decode which will say if its ADCS OR SBB THEN use carry in
    input  mul_signed,
    input  flag_source,
    input  cmp_signed,
    output [31:0] Y,
    output  carry_out,//this four flag c,v,z,n are output from add ,sub instruction means this will change its value after add or sub instruction
    output  overflow,
    output  zero,
    output  sign,
    output  GT,LT,EQ,
    output Z,N,V, // this are the comparator flags required for branch instruction
    output [6:0] flags_next // drives input for flag register 
);
    wire shift_carry;
    wire [15:0] operand_B=B_select_imm ? {12'b0, imm} : B;
    // ADDER
    wire [15:0] add_result;
    wire  add_carry,add_cin_msb;
    wire add_cin =use_carry_in ? carry_in : 1'b0;
    Cska_adder16_bit cska1 (
        .A(A),
        .B(operand_B),
        .Cin(add_cin),
        .Sum(add_result),
        .Cout(add_carry),
        .Cin_msb(add_cin_msb)
    );
    wire add_overflow ;
    assign add_overflow = add_carry ^ add_cin_msb;
    //SUBTRACTOR
    wire [15:0] sub_result;
    wire sub_borrow,sub_bin_msb,sub_bin;
    assign sub_bin =use_carry_in ? carry_in : 1'b0;
    
    cska_16bit_sub sub1 (
        .A(A),
        .B(operand_B),
        .Bin(sub_bin),
        .Diff(sub_result),
        .Bin_msb(sub_bin_msb),
        .Bout(sub_borrow)
    );
    wire  sub_overflow = sub_borrow ^ sub_bin_msb;
    // MULTIPLIER
    wire [31:0] mul_result;
    booth_multiplier_16bit multiplier1 (
        .A(A),
        .B(operand_B),
        .is_signed(mul_signed),
        .out(mul_result)
    );
    //COMPARATOR
    wire  cmp_carry;
    cmp_16_usingsub comparator1 (
        .A(A),
        .B(operand_B),
        .is_signed(cmp_signed),
        .BGT(GT),
        .BLT(LT),
        .BEQ(EQ),
        .Bout(cmp_carry),
        .Z(Z),
        .N(N),
        .V(V)
    );
    
   wire [15:0] shift_result;
    shifter_unit_combine shift1 (
        .data(A),
        .shift_amt(operand_B),
        .shift_type(Shift_type),//last bit of alu_sub_op denotes if operation is with B reg or imm
        .out(shift_result),
        .carry_out(shift_carry)
    );
    reg [31:0] result_reg;
    reg  carry_reg,overflow_reg;
   
   always @(*) begin

        result_reg = 32'b0;
        carry_reg  = 1'b0;
        overflow_reg = 1'b0;

        case (ALU_op)
            4'b0000: begin
                result_reg = {16'b0,add_result};
                carry_reg  = add_carry;
                overflow_reg = add_overflow;
            end
            4'b0001: begin
                result_reg = {16'b0,sub_result};
                carry_reg  = sub_borrow;
                overflow_reg = sub_overflow;
            end
            4'b0010: result_reg = {16'd0,(A & operand_B)};
            4'b0011:result_reg ={16'd0,( A | operand_B)};
            4'b0100:result_reg = {16'd0,(A ^ operand_B)};
            4'b0101: result_reg = {16'd0,~A};
            4'b0110: result_reg = mul_result;
            4'b0111: result_reg = 32'b0;//COMPARE
            4'b1000:begin
              result_reg = {16'd0,shift_result};
              carry_reg  = shift_carry;
              end
            4'b1001: result_reg = {16'b0,operand_B};//mov operation. pass b operation used also for loading opcode
            4'b1010: result_reg = {16'b0, A};   //pass a operation used for store operation as str [r1],r2 requires us first 
            //toaccess r1 value which is the adderess we want to store the value of r2 reg
            default: ;
        endcase
    end
     assign Y = result_reg;
    assign carry_out = carry_reg;
    assign overflow = overflow_reg;
    assign zero = (result_reg == 32'b0);
    assign sign = (ALU_op == 4'b0110) ? result_reg[31] : result_reg[15];//for multiply operation sign bit will be different
    wire [6:0] flags_alu = {zero, carry_out, sign, overflow, 3'b000};//why zero because for alu operation like add,sub we dont want flags to store gt lt eq values from before comparisions
    wire [6:0] flags_cmp = {Z,cmp_carry, N,V, GT, LT, EQ};
    assign flags_next = flag_source ? flags_cmp : flags_alu;
    
endmodule